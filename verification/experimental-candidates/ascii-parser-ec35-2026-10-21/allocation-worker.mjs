import fs from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {Session} from 'node:inspector';
import assert from 'node:assert/strict';
const [engine,scenario]=process.argv.slice(2);
assert.ok(['baseline','candidate'].includes(engine));
assert.ok(['reduction-512','dense-rt-192'].includes(scenario));
const modulePath=resolve(engine==='baseline'?'baseline/core.mjs':'dist/core.mjs');
const core=await import(pathToFileURL(modulePath));
const fixtureBytes=fs.readFileSync('inputs/'+scenario+'.json');
const fixture=JSON.parse(fixtureBytes),text=JSON.stringify(fixture.history);
const run=()=>fixture.operation==='shrink'?core.shrink_options_json(text,'{}'):core.analyze_options_json(text,'{}');
let output;for(let i=0;i<5;i++)output=run();
const session=new Session();session.connect();
const post=(method,params={})=>new Promise((yes,no)=>session.post(method,params,(error,result)=>error?no(error):yes(result)));
await post('HeapProfiler.enable');await post('Profiler.enable');
await post('Profiler.setSamplingInterval',{interval:500});
await post('HeapProfiler.startSampling',{samplingInterval:32768,includeObjectsCollectedByMajorGC:true,includeObjectsCollectedByMinorGC:true});
await post('Profiler.start');
for(let i=0;i<30;i++)output=run();
const cpu=await post('Profiler.stop');
const heap=await post('HeapProfiler.stopSampling');session.disconnect();
const hash=x=>createHash('sha256').update(x).digest('hex');
const allocations=[];function visit(n,parents){const path=[...parents,n.callFrame.functionName||'<anonymous>'];if(n.selfSize)allocations.push({path,bytes:n.selfSize});for(const child of n.children||[])visit(child,path);}visit(heap.profile.head,[]);
const result={schema:1,engine,scenario,diagnosticOnly:true,formalPerformanceMeasured:false,timingOrRssAcceptance:false,node:process.version,engineSha256:hash(fs.readFileSync(modulePath)),fixtureSha256:hash(fixtureBytes),outputSha256:hash(output),outputBytes:Buffer.byteLength(output),warmups:5,operations:30,totalSampledBytes:allocations.reduce((s,r)=>s+r.bytes,0),allocations:allocations.sort((a,b)=>b.bytes-a.bytes)};
fs.writeFileSync('receipts/allocation-'+engine+'-'+scenario+'.json',JSON.stringify(result,null,2)+'\n',{flag:'wx'});
fs.writeFileSync('receipts/cpu-'+engine+'-'+scenario+'.json',JSON.stringify(cpu)+'\n',{flag:'wx'});
fs.writeFileSync('receipts/heap-'+engine+'-'+scenario+'.json',JSON.stringify(heap)+'\n',{flag:'wx'});
console.log(JSON.stringify({engine,scenario,totalSampledBytes:result.totalSampledBytes,outputSha256:result.outputSha256}));
